from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'assets'/'intro'; OUT.mkdir(exist_ok=True)
first='''<g id="bamboo-bank"><path d="M84 126Q120 111 156 126L153 211Q120 227 87 211Z" fill="#40634f"/><ellipse cx="120" cy="126" rx="36" ry="11" fill="#849b76"/><path d="M106 126H134" stroke="#294b39" stroke-width="4" stroke-linecap="round"/><path d="M86 171Q120 184 154 171" stroke="#b5c4a6" stroke-width="2.3" fill="none"/><path d="M87 208Q120 220 153 208" stroke="#b5c4a6" stroke-width="2.3" fill="none"/></g><g id="coin"><circle cx="120" cy="88" r="13" fill="#bbad70"/><circle cx="120" cy="88" r="9" fill="none" stroke="#f5f7f2" stroke-width="1.2"/><path d="M120 83v10" stroke="#f5f7f2" stroke-width="1.5" stroke-linecap="round"/></g>'''
# Each culm shares the same floor; leaves are compact closed quadratic curves.
stalks=[(73,150,-8,'#8ca17e'),(95,102,-6,'#6d8860'),(121,54,1,'#40634f'),(146,85,7,'#5b7851'),(169,140,10,'#8ca17e')]
parts=[]
for x,top,lean,color in stalks:
 tip=x+lean
 parts.append(f'<path d="M{x-3} 224Q{x-3} 166 {tip-2} {top+3}Q{tip} {top-3} {tip+2} {top+3}Q{x+3} 166 {x+3} 224Z" fill="{color}"/>')
 for y in range(top+28,220,34):
  at=x+lean*(224-y)/(224-top)
  parts.append(f'<path d="M{at-3.2:.1f} {y}h6.4" stroke="#f5f7f2" stroke-width="1.4"/>')
def leaf(x,y,dx,dy,color):
 tx=x+dx;ty=y+dy;cx=x+dx*.35;cy=y+dy*.25
 return f'<path d="M{x} {y}Q{cx-dy*.18:.1f} {cy+dx*.18:.1f} {tx} {ty}Q{cx+dy*.12:.1f} {cy-dx*.12:.1f} {x} {y}Z" fill="{color}"/>'
leaves=[(121,92,-40,-32,'#40634f'),(121,94,34,-31,'#40634f'),(122,134,-32,-23,'#40634f'),(123,140,35,-27,'#40634f'),(149,123,38,-18,'#5b7851'),(149,125,15,-38,'#5b7851'),(146,167,33,-20,'#5b7851'),(93,138,-34,-23,'#6d8860'),(93,141,13,-31,'#6d8860'),(94,177,-31,-14,'#6d8860'),(69,176,-26,-20,'#8ca17e'),(73,202,-22,-12,'#8ca17e'),(173,178,27,-25,'#8ca17e'),(170,202,24,-15,'#8ca17e')]
last=''.join(parts)+''.join(leaf(*args) for args in leaves)
frame={'first':first,'last':last}
(ROOT/'intro-frames.js').write_text('// Generated by scripts/build_intro_frames.py. Editable vector endpoints.\nwindow.BambooFrames='+json.dumps(frame,separators=(',',':'))+';\n')
for key,art in frame.items():
 # Full phone composition, identical layout at both endpoints.
 svg=f'''<svg xmlns="http://www.w3.org/2000/svg" width="390" height="844" viewBox="0 0 390 844">
 <rect width="390" height="844" fill="#f5f7f2"/>
 <svg x="75" y="243" width="240" height="260" viewBox="0 0 240 260">{art}</svg>
 <text x="195" y="766" text-anchor="middle" font-family="Arial,sans-serif" font-size="30" font-weight="600" letter-spacing="-1.4" fill="#294b39">bamboo</text>
 </svg>'''
 (OUT/f'{key}-frame.svg').write_text(svg)
print('Wrote two vector endpoints and shared app artwork.')
